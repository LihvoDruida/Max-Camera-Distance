#!/usr/bin/env python3
"""Generate per-flavour .toc files from Max_Camera_Distance.toc.

tools/official_clients.json owns current products, regions and interfaces.
Max_Camera_Distance.toc owns the release version and shared metadata. Per-client TOCs are produced from it by
replacing flavour headers and, when required, applying a very small explicit
flavour override (Forever/Camelot needs a load-time marker before manifest.xml).

    python3 tools/generate_tocs.py          # write the files
    python3 tools/generate_tocs.py --check  # verify they are current (CI)
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADDON = "Max_Camera_Distance"
SOURCE = ROOT / f"{ADDON}.toc"

# Current official products/regions are the source of truth. Historical API
# probes remain regressions; they must not expand the advertised TOC scope.
SUPPORT = json.loads((ROOT / "tools/official_clients.json").read_text(encoding="utf-8"))
RETAIL = next(item for item in SUPPORT["products"] if item["key"] == "retail")
MAINLINE_INTERFACE = ", ".join(str(value) for value in [RETAIL["interface"], *RETAIL.get("test_interfaces", [])])
FLAVOURS = {}
for item in SUPPORT["products"]:
    interfaces = [item["interface"], *item.get("test_interfaces", [])]
    for suffix in item["suffixes"]:
        FLAVOURS[suffix] = {
            "interface": ", ".join(map(str, interfaces)),
            "flavor": item["flavor"],
            "expansion": item["expansion"],
            "extra_files": tuple(item.get("extra_files", [])),
        }
FLAVOURS["Classic"] = {
    "interface": ", ".join(str(item["interface"]) for item in SUPPORT["products"] if item["key"] not in ("retail", "forever")),
    "flavor": "classic",
    "expansion": "Current Classic Family",
}
OBSOLETE = [f"{ADDON}-Era.toc", f"{ADDON}-BCC.toc", f"{ADDON}-Mists.toc", f"{ADDON}_Cata.toc"]


def lua_value(value, level=0):
    """Serialize the small support snapshot as data; no client JSON parser."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return "{ " + ", ".join(lua_value(item, level + 1) for item in value) + " }"
    if isinstance(value, dict):
        indent = "    " * (level + 1)
        return "{\n" + "\n".join(indent + "[" + lua_value(key) + "] = " + lua_value(item, level + 1) + "," for key, item in value.items()) + "\n" + "    " * level + "}"
    raise TypeError(type(value))


def support_lua():
    return "-- Generated by tools/generate_tocs.py; edit tools/official_clients.json.\nlocal _, ns = ...\nns.ClientSupport = " + lua_value(SUPPORT) + "\n"

HEADER = re.compile(r"^## ([^:]+):.*$")
REQUIRED = ("Interface", "X-Flavor", "X-Expansion")


def render(
    source_text: str,
    interface: str,
    flavor: str,
    expansion: str,
    metadata=None,
    extra_files=(),
) -> str:
    """Render one flavour without allowing generated TOCs to drift manually."""
    replacements = {
        "Interface": interface,
        "X-Flavor": flavor,
        "X-Expansion": expansion,
    }
    if metadata:
        replacements.update(metadata)

    seen = set()
    out = []
    for line in source_text.split("\n"):
        match = HEADER.match(line)
        if match:
            key = match.group(1)
            if key in replacements:
                seen.add(key)
                out.append(f"## {key}: {replacements[key]}")
                continue
        out.append(line)

    missing = set(REQUIRED) - seen
    if missing:
        raise SystemExit(
            f"{SOURCE.name} is missing required header(s): {', '.join(sorted(missing))}"
        )

    # Forever/Camelot must set its load-time marker before shared files execute.
    if extra_files:
        try:
            manifest_index = out.index("manifest.xml")
        except ValueError as exc:
            raise SystemExit(f"{SOURCE.name} is missing manifest.xml") from exc
        for filename in reversed(tuple(extra_files)):
            if filename not in out:
                out.insert(manifest_index, filename)

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if any generated file is missing or stale",
    )
    args = parser.parse_args()

    if not SOURCE.exists():
        raise SystemExit(f"source TOC not found: {SOURCE}")

    source_text = SOURCE.read_text(encoding="utf-8")

    support_path = ROOT / "ClientSupport.lua"
    support_text = support_lua()
    if args.check:
        if not support_path.exists() or support_path.read_text(encoding="utf-8") != support_text:
            print("ClientSupport.lua is stale; run tools/generate_tocs.py", file=sys.stderr)
            return 1
    else:
        support_path.write_text(support_text, encoding="utf-8")

    # Keep the source itself honest about its Mainline headers.
    expected_source = render(
        source_text,
        MAINLINE_INTERFACE,
        "mainline",
        "Midnight",
    )
    problems = []

    if expected_source != source_text:
        if args.check:
            problems.append(f"{SOURCE.name} (Mainline headers are stale)")
        else:
            SOURCE.write_text(expected_source, encoding="utf-8")
            print(f"updated  {SOURCE.name}")
        source_text = expected_source

    for suffix, config in sorted(FLAVOURS.items()):
        target = ROOT / f"{ADDON}_{suffix}.toc"
        content = render(
            source_text,
            config["interface"],
            config["flavor"],
            config["expansion"],
            metadata=config.get("metadata"),
            extra_files=config.get("extra_files", ()),
        )

        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                problems.append(target.name)
        else:
            target.write_text(content, encoding="utf-8")
            print(f"wrote    {target.name}  (Interface {config['interface']})")

    for name in OBSOLETE:
        stale = ROOT / name
        if stale.exists():
            if args.check:
                problems.append(f"{name} (out-of-scope or obsolete TOC - delete it)")
            else:
                stale.unlink()
                print(f"removed  {name}  (out-of-scope or obsolete TOC)")

    if problems:
        print("Stale or missing TOC files:", file=sys.stderr)
        for name in problems:
            print(f"  - {name}", file=sys.stderr)
        print("Run: python3 tools/generate_tocs.py", file=sys.stderr)
        return 1

    if args.check:
        print("All .toc files are up to date.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
